"""
Generate the browser demo's data file.

Writes web/summarizer-data.js with scikit-learn's English stop-word list
(the one TfidfVectorizer(stop_words="english") uses in summarize.py) and
the built-in SAMPLE article, so the browser version picks the same
sentences and keywords as the Python version:

    python gen_web_data.py
"""

import json
from pathlib import Path

from sklearn.feature_extraction.text import ENGLISH_STOP_WORDS

from summarize import SAMPLE

HERE = Path(__file__).parent
OUT_FILE = HERE / "web" / "summarizer-data.js"


def main() -> None:
    OUT_FILE.parent.mkdir(exist_ok=True)
    with OUT_FILE.open("w", encoding="utf-8") as file:
        file.write("// Generated by gen_web_data.py - do not edit by hand.\n")
        file.write(f"const SKLEARN_STOP_WORDS = {json.dumps(sorted(ENGLISH_STOP_WORDS))};\n")
        file.write(f"const SAMPLE_TEXT = {json.dumps(SAMPLE, ensure_ascii=False)};\n")
    print(f"Wrote {OUT_FILE}")


if __name__ == "__main__":
    main()
